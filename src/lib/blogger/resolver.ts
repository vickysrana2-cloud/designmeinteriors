/**
 * Server-side Blogger Video Resolver Utility.
 * Resolves Blogger native video <object class="BLOG_video_class" contentid="..."> elements
 * into actual authenticated player URLs (https://www.blogger.com/video.g?token=AD6v5d...&origin=...)
 * by inspecting the public Blogger post page HTML during server-side generation.
 */

interface ResolvedVideoMap {
  [contentId: string]: string;
}

/**
 * Parses public Blogger HTML to map each contentid to its real video.g player iframe URL.
 */
export function extractBloggerVideoUrls(publicHtml: string): ResolvedVideoMap {
  const map: ResolvedVideoMap = {};
  if (!publicHtml || typeof publicHtml !== "string") return map;

  try {
    // Pattern matches iframe tags generated by Blogger server renderer:
    // e.g. <iframe ... id="BLOGGER-video-8f5b002dfbbe3bdc-13746" ... src="https://www.blogger.com/video.g?token=AD6v5d...&origin=..." ...>
    const iframeRegex = /<iframe[^>]+src=["']([^"']+)["'][^>]*>/gi;
    let match: RegExpExecArray | null;

    while ((match = iframeRegex.exec(publicHtml)) !== null) {
      const fullTag = match[0];
      let src = match[1];

      if (!src) continue;

      // Decode HTML entities in URL (e.g. &amp; -> &)
      src = src.replace(/&amp;/g, "&");

      // Match contentid from id="BLOGGER-video-{contentid}-{rand}" or from tag content
      const idMatch =
        fullTag.match(/BLOGGER-video-([a-f0-9]+)-/i) ||
        fullTag.match(/id=["']BLOG_video-([a-f0-9]+)["']/i);

      if (idMatch && idMatch[1]) {
        const contentId = idMatch[1];
        map[contentId] = src;
      } else {
        // Fallback: search if src or tag contains contentid substring
        const tokenMatch = src.match(/token=([^&]+)/);
        if (tokenMatch) {
          const contentIdSearch = fullTag.match(/contentid=["']([a-f0-9]+)["']/i);
          if (contentIdSearch && contentIdSearch[1]) {
            map[contentIdSearch[1]] = src;
          }
        }
      }
    }
  } catch (err) {
    console.error("Error extracting Blogger video URLs from public HTML:", err);
  }

  return map;
}

/**
 * Pre-processes Blogger post content HTML server-side.
 * Resolves all native <object class="BLOG_video_class" contentid="..."> tags into verified player iframes.
 * GUARANTEE: Never throws an unhandled exception. Returns safe HTML fallback if anything fails.
 */
export async function resolveBloggerPostVideos(
  contentHtml: string,
  bloggerPostUrl?: string
): Promise<string> {
  if (!contentHtml || typeof contentHtml !== "string") {
    return contentHtml || "";
  }

  // Quick check: if post doesn't contain Blogger video object, return immediately
  if (!contentHtml.includes("BLOG_video_class")) {
    return contentHtml;
  }

  try {
    // Find all contentid values in post HTML
    const objectRegex =
      /<object[^>]*class=["'][^"']*BLOG_video_class[^"']*["'][^>]*contentid=["']([^"']+)["'][^>]*>[\s\S]*?<\/object>/gi;
    const contentIds: string[] = [];
    let objMatch: RegExpExecArray | null;

    while ((objMatch = objectRegex.exec(contentHtml)) !== null) {
      if (objMatch[1]) {
        contentIds.push(objMatch[1]);
      }
    }

    if (contentIds.length === 0) return contentHtml;

    // Fetch public Blogger post HTML if post URL is valid
    let videoMap: ResolvedVideoMap = {};
    if (
      bloggerPostUrl &&
      typeof bloggerPostUrl === "string" &&
      (bloggerPostUrl.startsWith("http://") || bloggerPostUrl.startsWith("https://"))
    ) {
      try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 5000); // 5s timeout

        const res = await fetch(bloggerPostUrl, {
          headers: {
            "User-Agent":
              "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
          },
          signal: controller.signal,
        });

        clearTimeout(timeoutId);

        if (res.ok) {
          const publicHtml = await res.text();
          videoMap = extractBloggerVideoUrls(publicHtml);
        }
      } catch (fetchErr) {
        console.warn(`Failed to fetch public Blogger post at ${bloggerPostUrl}:`, fetchErr);
      }
    }

    // Replace each <object> tag with a resolved <iframe src="..."> tag while preserving width/height
    return contentHtml.replace(
      /<object([^>]*)>[\s\S]*?<\/object>/gi,
      (match, attribsStr) => {
        if (!attribsStr.includes("BLOG_video_class")) return match;

        const contentIdMatch = attribsStr.match(/contentid=["']([^"']+)["']/i);
        const widthMatch = attribsStr.match(/width=["']([^"']+)["']/i);
        const heightMatch = attribsStr.match(/height=["']([^"']+)["']/i);

        const contentId = contentIdMatch ? contentIdMatch[1] : "";
        const width = widthMatch ? widthMatch[1] : "322";
        const height = heightMatch ? heightMatch[1] : "241";

        const resolvedSrc = contentId ? videoMap[contentId] : null;

        if (resolvedSrc) {
          return `<iframe class="b-hbp-video b-uploaded" src="${resolvedSrc}" width="${width}" height="${height}" allowfullscreen="allowfullscreen" frameborder="0"></iframe>`;
        }

        // Safe Fallback if resolution fails or public page was unreachable
        if (bloggerPostUrl) {
          return `<div class="blogger-video-fallback my-6 p-4 rounded-2xl border border-[#D7D0C5] bg-[#E8E1D7]/30 text-center"><p class="text-sm text-[#706B63] mb-2">Native Blogger Video</p><a href="${bloggerPostUrl}" target="_blank" rel="noopener noreferrer" class="inline-flex items-center gap-2 text-xs font-semibold uppercase tracking-wider text-[#9A8060] underline">Watch Video on Blogger ↗</a></div>`;
        }

        return match;
      }
    );
  } catch (topLevelError) {
    console.error("Top-level exception in resolveBloggerPostVideos:", topLevelError);
    return contentHtml; // Always return original HTML safely if any unexpected error occurs
  }
}
